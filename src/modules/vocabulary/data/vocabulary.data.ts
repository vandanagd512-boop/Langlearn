// Retrieve vocabulary list for a specific language
export function getVocabularyForLanguage(langCode: string): VocabularyWord[] {
  const code = (langCode || 'kn').toLowerCase();
  if (VOCABULARY_DATABASE[code] && VOCABULARY_DATABASE[code].length > 0) {
    return VOCABULARY_DATABASE[code];
  }
  return generateSynthesizedWordPack(code);
}

// Get daily vocabulary word
export function getDailyVocabularyWord(langCode: string): VocabularyWord {
  const list = getVocabularyForLanguage(langCode);
  return list[0] || VOCABULARY_DATABASE.kn[0];
}
