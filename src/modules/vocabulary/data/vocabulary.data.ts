// Helper to convert raw blueprint to VocabularyWord
function formatWordList(rawList: RawWordBlueprint[], langCode: string): VocabularyWord[] {
  return rawList.map((w, index) => ({
    id: `${langCode}-v-${index + 1}`,
    langCode,
    word: w.word,
    romanized: w.romanized,
    phonetic: w.phonetic,
    meaning: w.meaning,
    partOfSpeech: w.partOfSpeech,
    category: w.category,
    categoryLabel: w.categoryLabel,
    difficulty: w.difficulty,
    exampleSentence: w.exampleSentence,
    exampleRomanized: w.exampleRomanized,
    exampleTranslation: w.exampleTranslation,
    culturalNote: w.culturalNote,
    audioLangCode: langCode === 'en' ? 'en-US' : `${langCode}-IN`,
    learnedAt: index < 5 ? 'Today' : index < 15 ? 'Yesterday' : `${(index % 7) + 2} days ago`,
    masteryStatus: index < 10 ? 'mastered' : index < 25 ? 'learning' : index < 35 ? 'review_due' : 'new',
    streakDays: Math.max(1, (50 - index) % 12),
  }));
}

